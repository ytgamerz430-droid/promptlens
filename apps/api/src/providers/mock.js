/**
 * Mock provider for development and testing. No network, no cost.
 * Outputs are clearly labeled as demo samples — never mistaken for real AI output.
 */

export const name = 'mock';
export const defaultModel = 'mock';

const SAMPLE_KEYWORDS = [
  'sample', 'demo image', 'placeholder', 'test photo', 'mock generation',
  'illustration', 'stock style', 'creative asset', 'visual reference', 'concept art',
  'digital artwork', 'high resolution', 'studio lighting', 'shallow depth of field',
  'vibrant colors', 'minimal composition', 'detailed texture', 'soft shadows',
  'modern aesthetic', 'clean background', 'natural light', 'sharp focus',
  'artistic style', 'trending theme', 'versatile use', 'commercial ready',
  'lifestyle mood', 'editorial look', 'authentic feel', 'timeless design',
  'bold contrast', 'warm tones', 'cool tones', 'dynamic angle',
  'close-up detail', 'wide composition', 'negative space', 'balanced layout',
  'fine art', 'contemporary', 'inspiration', 'creative project',
  'visual story', 'mood board', 'design element', 'content creation',
  'social media', 'marketing asset', 'brand friendly', 'evergreen topic',
];

export function create() {
  async function generateVision({ imageBuffer, mimeType, systemPrompt, userPrompt, extra = {} }) {
    const tool = extra.tool || 'prompt';
    const sizeKb = Math.max(1, Math.round((imageBuffer?.length || 0) / 1024));
    const label = `[demo output — mock provider, ${sizeKb} KB ${mimeType || 'image'}]`;

    if (tool === 'metadata') {
      const limits = extra.limits || {};
      const min = limits.keywordMin ?? 5;
      const max = limits.keywordMax ?? 25;
      const count = Math.max(min, Math.min(max, Math.max(min, 12)));
      const keywords = SAMPLE_KEYWORDS.slice(0, count);
      return {
        text: JSON.stringify({
          title: 'Demo title describing the uploaded image for the mock provider',
          keywords,
          description: 'This is a demo description generated by the mock provider. Connect a real AI provider in Settings to generate real metadata.',
        }),
        model: 'mock',
      };
    }

    if (tool === 'deep') {
      const components = [
        'Subject', 'Composition', 'Lighting', 'Color palette', 'Style',
        'Mood', 'Background', 'Texture', 'Perspective', 'Details',
      ].map((c) => ({ name: c, detail: `Demo ${c.toLowerCase()} note for the uploaded image (mock provider).` }));
      return {
        text: JSON.stringify({
          components,
          summary: 'Demo deep-analysis summary produced by the mock provider. Connect a real provider in Settings for a genuine breakdown.',
        }),
        model: 'mock',
      };
    }

    if (tool === 'ip-risk') {
      return {
        text: JSON.stringify({
          risk: 'low',
          findings: ['Demo finding: no obvious trademark or logo detected (mock provider).'],
          summary: 'Demo IP-risk summary from the mock provider. Connect a real provider in Settings for a genuine assessment.',
        }),
        model: 'mock',
      };
    }

    return {
      text:
        `${label} A richly detailed scene rendered in a clean, modern photographic style — ` +
        'balanced composition, soft natural lighting, and vivid yet harmonious color. ' +
        'Connect a real AI provider in Settings to generate a genuine prompt from your image.',
      model: 'mock',
    };
  }

  async function testConnection() {
    return { ok: true, latencyMs: 2, model: 'mock' };
  }

  return { generateVision, testConnection };
}
